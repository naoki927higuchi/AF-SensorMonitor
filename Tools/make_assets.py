"""Cuts the app's mascot and launcher icon out of the user-provided sheet (Reference/UserProvided/透過版.png).

Run from the repository root:  python Tools/make_assets.py   (needs Pillow and NumPy)
Outputs go to app/src/main/res/ (drawable-nodpi and drawable). The source images are not modified.
"""
from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SHEET = ROOT / "Reference" / "UserProvided" / "透過版.png"
RES = ROOT / "app" / "src" / "main" / "res"

# Boxes (left, top, right, bottom) of the large drawings in the sheet.
NORMAL_BOX = (118, 12, 704, 562)
REACTING_BOX = (784, 12, 1398, 562)
ICON_BOX = (1560, 82, 2024, 534)

MASCOT_PX = 256
QUIET_BRIGHTNESS = 0.6  # the mascot while the sensors are quiet


def keep_main_parts(img: Image.Image, min_share: float = 0.05) -> Image.Image:
    """Removes stray pieces of neighbouring drawings: keeps opaque regions at least min_share of the largest."""
    arr = np.array(img)
    mask = arr[:, :, 3] > 8
    h, w = mask.shape
    label = np.zeros((h, w), dtype=np.int32)
    sizes = [0]
    for y in range(h):
        for x in range(w):
            if mask[y, x] and not label[y, x]:
                n = len(sizes)
                label[y, x] = n
                queue = deque([(y, x)])
                count = 0
                while queue:
                    cy, cx = queue.popleft()
                    count += 1
                    for ny, nx in ((cy - 1, cx), (cy + 1, cx), (cy, cx - 1), (cy, cx + 1)):
                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not label[ny, nx]:
                            label[ny, nx] = n
                            queue.append((ny, nx))
                sizes.append(count)
    largest = max(sizes)
    keep = np.array([s >= largest * min_share for s in sizes])
    keep[0] = False
    # Keep faint (alpha <= 8) edge pixels next to kept regions as they are; drop everything in removed regions.
    removed = (label > 0) & ~keep[label]
    arr[removed, 3] = 0
    return Image.fromarray(arr)


def square(img: Image.Image, side: int) -> Image.Image:
    """Bottom-left aligned on a square canvas, so both expressions line up when swapped."""
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.alpha_composite(img, (0, side - img.height))
    return canvas


def dim(img: Image.Image, factor: float) -> Image.Image:
    arr = np.array(img).astype(np.float32)
    arr[:, :, :3] *= factor
    return Image.fromarray(arr.clip(0, 255).astype(np.uint8))


def main() -> None:
    sheet = Image.open(SHEET).convert("RGBA")
    normal = keep_main_parts(sheet.crop(NORMAL_BOX))
    reacting = keep_main_parts(sheet.crop(REACTING_BOX))
    side = max(normal.width, normal.height, reacting.width, reacting.height)
    out = RES / "drawable-nodpi"
    out.mkdir(parents=True, exist_ok=True)
    normal_sq = square(normal, side).resize((MASCOT_PX, MASCOT_PX), Image.LANCZOS)
    reacting_sq = square(reacting, side).resize((MASCOT_PX, MASCOT_PX), Image.LANCZOS)
    normal_sq.save(out / "kuro_normal.png", optimize=True)
    dim(normal_sq, QUIET_BRIGHTNESS).save(out / "kuro_quiet.png", optimize=True)
    reacting_sq.save(out / "kuro_reacting.png", optimize=True)

    # Adaptive launcher icon (108 dp canvas, 72 dp visible, masks as small as a 72 dp circle). The inside of the
    # rounded square (without its corners) is drawn at 64 dp with feathered edges so the C and its waves stay
    # inside a circular mask; the background layer is the picture's dark edge color, so the edges blend.
    icon = sheet.crop(ICON_BOX)
    cx, cy = icon.width // 2, icon.height // 2
    half = 190
    inner = icon.crop((cx - half, cy - half, cx + half, cy + half)).convert("RGBA")
    out_icon = RES / "mipmap-xxxhdpi"
    out_icon.mkdir(parents=True, exist_ok=True)
    edge = np.concatenate([np.array(inner)[0, :, :3], np.array(inner)[-1, :, :3],
                           np.array(inner)[:, 0, :3], np.array(inner)[:, -1, :3]])
    r, g, b = (int(v) for v in np.median(edge, axis=0))
    (RES / "values" / "icon_colors.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by Tools/make_assets.py -->\n<resources>\n'
        f'    <color name="icon_background">#FF{r:02X}{g:02X}{b:02X}</color>\n</resources>\n', encoding="utf-8")
    size = 256
    fg_img = inner.resize((size, size), Image.LANCZOS)
    feather = 28
    yy, xx = np.mgrid[0:size, 0:size]
    edge_dist = np.minimum(np.minimum(xx, size - 1 - xx), np.minimum(yy, size - 1 - yy))
    alpha = np.array(fg_img)[:, :, 3].astype(np.float32) * np.clip(edge_dist / feather, 0, 1)
    arr = np.array(fg_img)
    arr[:, :, 3] = alpha.astype(np.uint8)
    fg = Image.new("RGBA", (432, 432), (0, 0, 0, 0))
    fg.alpha_composite(Image.fromarray(arr), ((432 - size) // 2, (432 - size) // 2))
    fg.save(out_icon / "ic_launcher_foreground.png", optimize=True)


if __name__ == "__main__":
    main()
